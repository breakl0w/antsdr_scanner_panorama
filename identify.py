# ================================================================
#  identify.py — идентификация сигналов по частоте
# ================================================================

SIGNAL_MAP = [
    (88,    108,    "FM радио"),
    (108,   137,    "Авиация VHF"),
    (137,   138,    "Метеоспутники NOAA"),
    (380,   400,    "Экстренные службы TETRA"),
    (400,   470,    "PMR/LPD/CB UHF"),
    (860,   960,    "GSM-900"),
    (1710,  1880,   "GSM-1800/DCS"),
    (1920,  2170,   "3G UMTS"),
    (2400,  2483.5, "Wi-Fi/BT 2.4G"),
    (5150,  5850,   "Wi-Fi 5GHz"),
]


def identify(freq_hz: float) -> str:
    f = freq_hz / 1e6
    for lo, hi, name in SIGNAL_MAP:
        if lo <= f <= hi:
            return name
    return "Неизвестный"
